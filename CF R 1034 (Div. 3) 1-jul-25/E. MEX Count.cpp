int solve() {
    // Code aquí
    int n;
    cin >> n;
    vi a(n);
    lee(n, a);
    ord(a);

    if (a[0] != 0){
        for (int i = 0; i<=n; i++){
            cout << 1 << " ";
        }
        cout << endl;
        return 0;
    }
    vi counter = {1};
    int reps = 0;
    for (int i = 1; i<n; i++){
        if (a[i] == a[i-1]){
            counter[a[i]]++;
            reps++;
        } else if (a[i] == a[i-1]+1){
            counter.emplace_back(1);
        } else {
            reps += n-i; 
            break;
        }
    }

    counter.emplace_back(0);

    vi sol(n+2, 0);
    for (int i = 0; i<counter.size(); i++){
        int left = counter[i];
        int right = reps+counter.size()-i;
        sol[left]++;
        sol[right]--;
    }
    int res = 0;
    for (int i = 0; i<sol.size()-1; i++){
        res+=sol[i];
        cout << res << " ";
    }
    cout << endl;

    return 0;
}

