int solve() {
    // Code aquí
    lli n, x; cin >> n >> x;
    vll a(n); for (int i = 0; i<n; i++) cin >> a[i];
    // Para hacer el algoritmo utilizaremos dp, nos basaremos en la siguiente afirmación:
    // Dada una l, si la suma del rango [l, m] es 0, el número de rangos que no son igual a 0 son todos los rangos de [l,r] tal que el rango de [m,r] no sea igual a 0 y [l, m]
    // Sabiendo esto, el problema se reduce a asignar a cada uno de los números cuantos rangos que dan 0 existen y asignar la posición del primer elemento a su derecha donde de 0
    // Usando luego dp, calcula de derecha a izquierda los intervalos

    vll rightElement(n, n); // Para cada l, el primer número r a su derecha que al hacer la suma de todos los elementos entre l y r da más que x
    int left = 0;
    int right = 0;
    lli suma = 0;
    while (right < n){
        if (suma <= x) {
            suma += a[right];
            right++;
        } else {
            rightElement[left] = right-1;
            suma -= a[left];
            left++;
        }
    }
    while(suma > x){
        rightElement[left] = right-1;
        suma -= a[left];
        left++;
    }

    vll dp(n+2, 0); // Cuantos intervalos válidos hay 
    for (int i = n-1; i>=0; i--){
        int limR = rightElement[i];
        dp[i] = dp[limR+1] + limR - i;
    }
    lli sol = 0;
    for (auto val:dp) sol+=val;

    cout << sol << endl;

    return 0;
}

